#!/usr/bin/env python3
"""Write paper/claims.tex (one \\newcommand per claim) from claims.json.  scripts/verify.py fails if the
committed paper/claims.tex differs from what this script produces.

Plain string claims become \\cl<key>.  Integers with 5 or more digits are printed with {,} separators.
Derived macros (scientific notation, CPU hours, percentages) are computed here from the integer claims,
so the paper never carries a number that is not tied to claims.json."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORD = {16: 'Sixteen', 17: 'Seventeen', 18: 'Eighteen', 19: 'Nineteen', 20: 'Twenty'}


def grouped(v, sep='{,}'):
    head = len(v) % 3 or 3
    return sep.join([v[:head]] + [v[i:i + 3] for i in range(head, len(v), 3)])


def tex(v):
    if v.isdigit() and len(v) >= 5:
        return grouped(v)
    return v


def sci(x, digits=2):
    """3562197100 -> 3.6\\times10^{9} (digits significant figures)."""
    e = len(str(int(x))) - 1
    m = round(x / 10 ** e, digits - 1)
    if m >= 10:
        m /= 10; e += 1
    return '%.*f\\times10^{%d}' % (digits - 1, m, e)


def cell(v):
    return grouped(v, '\\,') if v.isdigit() and len(v) >= 4 else v


def render():
    c = json.loads((ROOT / 'claims.json').read_text())
    out = ['% Generated by scripts/make_claims_tex.py from claims.json -- do not edit by hand.']
    for k, v in c.items():
        if not k.isalpha() or not isinstance(v, str):        # data-only entries (a_known, sha_*, ...) get no macro
            continue
        out.append(r'\newcommand{\cl%s}{%s}' % (k, tex(v)))
    big = [n for n in WORD if str(n) in c['runs']]
    for n in big:
        w = WORD[n]; r = c['runs'][str(n)]
        out.append(r'\newcommand{\clLeaves%s}{%s}' % (w, tex(r['leaves'])))
        out.append(r'\newcommand{\clLeaves%sSci}{%s}' % (w, sci(int(r['leaves']))))
        out.append(r'\newcommand{\clFlows%sSci}{%s}' % (w, sci(int(r['flows']))))
        out.append(r'\newcommand{\clCpuSec%s}{%s}' % (w, tex(str(round(float(r['cpu_seconds']))))))
        out.append(r'\newcommand{\clCpuH%s}{%.1f}' % (w, float(r['cpu_seconds']) / 3600))
    for n in sorted(int(k) for k in c['pqv_parts']):
        p = c['pqv_parts'][str(n)]
        out.append(r'\newcommand{\clPqvParts%s}{%d}' % (WORD[n], len(p['parts'])))
        out.append(r'\newcommand{\clPqvLeaves%s}{%s}' % (WORD[n], tex(p['leaves'])))
        out.append(r'\newcommand{\clPqvFrac%s}{%.1f}' % (WORD[n], 100 * int(p['leaves']) / int(c['runs'][str(n)]['leaves'])))
    for n in sorted(int(k) for k in c['lp']):
        w = WORD[n]
        out.append(r'\newcommand{\clLpMax%s}{%.2f}' % (w, float(c['lp'][str(n)]['max_bound_float'])))
    for n in big:
        w = WORD[n]
        out.append(r'\newcommand{\clT%s}{%s}' % (w, c['runs'][str(n)]['T']))
    g = [int(c['runs'][str(n + 1)]['leaves']) / int(c['runs'][str(n)]['leaves']) for n in range(15, max(big))]
    out.append(r'\newcommand{\clGrowthMin}{%.1f}' % min(g))
    out.append(r'\newcommand{\clGrowthMax}{%.1f}' % max(g))
    rows = []
    for n in sorted(c['runs'], key=int):
        r = c['runs'][n]
        rows.append(' & '.join([n, r['a'], r['T'], cell(r['leaves']), r['searched'], r['time_tex']]) + r'\\')
    out.append(r'\newcommand{\clRunRows}{%s}' % '\n'.join(rows))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    path = ROOT / 'paper' / 'claims.tex'
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        ok = path.exists() and path.read_text() == render()
        print('claims.tex in sync with claims.json:', ok)
        sys.exit(0 if ok else 1)
    path.write_text(render())
    print('wrote', path)
